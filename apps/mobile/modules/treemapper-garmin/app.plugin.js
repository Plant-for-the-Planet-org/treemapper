const {
  withAndroidManifest,
  withInfoPlist,
  createRunOncePlugin,
} = require('expo/config-plugins')

/**
 * The native configuration the Connect IQ link needs on both platforms.
 *
 * It lives beside the native code rather than in `apps/mobile/plugins/`
 * because the two are one unit: the Swift reads the URL scheme this plugin
 * writes, and a build where only one of them changed is broken. Expo
 * autolinking finds the module under `modules/` on its own, but a config
 * plugin is never automatic, so `app.json` still names this file.
 *
 * Everything here has to be a plugin and not a hand edit: `android/` and
 * `ios/` are gitignored and regenerated by `expo prebuild`, so a change made
 * in either folder is lost on the next run.
 */

const GARMIN_CONNECT_PACKAGE = 'com.garmin.android.apps.connectmobile'

/** The URL scheme Garmin Connect uses to query whether it is installed. */
const GCM_QUERY_SCHEME = 'gcm-ciq'

/**
 * The scheme Garmin Connect returns the chosen devices on.
 *
 * Deliberately not the app's own `treemapper` scheme. Garmin Connect answers a
 * device selection by opening a URL, and routing that through the app's deep
 * link handling would mean every Garmin round trip looks like a user following
 * a TreeMapper link. A separate scheme keeps the two apart, and Garmin's guide
 * asks for one unlikely to collide with another app.
 */
const DEFAULT_URL_SCHEME = 'treemapper-ciq'

/** Where the Swift reads the scheme back, so one value defines it. */
const URL_SCHEME_INFO_KEY = 'TreeMapperGarminUrlScheme'

const BLUETOOTH_REASON =
  'TreeMapper uses Bluetooth to read positions from your Garmin device.'

/**
 * Android 11 and later hide other installed packages from an app by default.
 * Every call the Connect IQ companion SDK makes on Android goes THROUGH Garmin
 * Connect Mobile to reach the device, so without this `<queries>` entry the SDK
 * cannot find it and initialisation fails with a confusing "service
 * unavailable" on a phone where Garmin Connect is installed and working.
 *
 * This is the single most common reason a Connect IQ Android integration works
 * in a tutorial and not in a real app.
 *
 * The module declares the same entry in its own library manifest, and a merge
 * of the two collapses into one. It is repeated here because the app manifest
 * is what a reviewer reads. The Bluetooth permissions come from that library
 * manifest alone: listing them in `app.json` as well would only duplicate them.
 */
const withGarminAndroid = config =>
  withAndroidManifest(config, cfg => {
    const manifest = cfg.modResults?.manifest
    if (!manifest) {
      throw new Error('withGarminLink: no <manifest> in the Android manifest')
    }

    manifest.queries = manifest.queries ?? []
    if (manifest.queries.length === 0) {
      manifest.queries.push({})
    }

    const queries = manifest.queries[0]
    queries.package = queries.package ?? []

    const already = queries.package.some(
      entry => entry?.$?.['android:name'] === GARMIN_CONNECT_PACKAGE,
    )
    if (!already) {
      queries.package.push({ $: { 'android:name': GARMIN_CONNECT_PACKAGE } })
    }

    return cfg
  })

/**
 * The iOS half, which is four separate requirements that all fail quietly.
 *
 *  1. **`LSApplicationQueriesSchemes` must list `gcm-ciq`.** It is how the SDK
 *     checks whether Garmin Connect is installed. Without it the SDK decides
 *     GCM is missing on a phone where it is running.
 *  2. **A URL scheme of our own.** Garmin Connect hands the chosen devices back
 *     by opening it. No scheme, no device list, and the picker looks like it
 *     did nothing.
 *  3. **`CFBundleDisplayName` must exist.** Garmin's guide is explicit that the
 *     return URL fails silently without it. Expo sets it from the app name, so
 *     this only fills a gap.
 *  4. **A Bluetooth usage string.** The SDK drives Core Bluetooth directly on
 *     iOS, unlike Android where Garmin Connect owns the radio, so the App Store
 *     rejects a build without one.
 */
const withGarminIos = (config, { urlScheme }) =>
  withInfoPlist(config, cfg => {
    const plist = cfg.modResults

    const queries = Array.isArray(plist.LSApplicationQueriesSchemes)
      ? plist.LSApplicationQueriesSchemes
      : []
    if (!queries.includes(GCM_QUERY_SCHEME)) {
      queries.push(GCM_QUERY_SCHEME)
    }
    plist.LSApplicationQueriesSchemes = queries

    const urlTypes = Array.isArray(plist.CFBundleURLTypes)
      ? plist.CFBundleURLTypes
      : []
    const hasScheme = urlTypes.some(entry =>
      (entry?.CFBundleURLSchemes ?? []).includes(urlScheme),
    )
    if (!hasScheme) {
      urlTypes.push({
        CFBundleURLName: 'org.pftp.treemapper.garmin',
        CFBundleURLSchemes: [urlScheme],
      })
    }
    plist.CFBundleURLTypes = urlTypes

    // The native side reads this rather than hardcoding the scheme, so the two
    // cannot drift apart.
    plist[URL_SCHEME_INFO_KEY] = urlScheme

    if (!plist.CFBundleDisplayName) {
      plist.CFBundleDisplayName = config.name ?? '$(PRODUCT_NAME)'
    }

    if (!plist.NSBluetoothAlwaysUsageDescription) {
      plist.NSBluetoothAlwaysUsageDescription = BLUETOOTH_REASON
    }
    if (!plist.NSBluetoothPeripheralUsageDescription) {
      plist.NSBluetoothPeripheralUsageDescription = BLUETOOTH_REASON
    }

    return cfg
  })

const withGarminLink = (config, props = {}) => {
  const urlScheme = props.urlScheme ?? DEFAULT_URL_SCHEME
  return withGarminIos(withGarminAndroid(config), { urlScheme })
}

module.exports = createRunOncePlugin(
  withGarminLink,
  'treemapper-garmin',
  '1.0.0',
)
