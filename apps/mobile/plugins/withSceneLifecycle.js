const { withAppDelegate, withInfoPlist } = require('expo/config-plugins')

/**
 * Adopts the UIScene life cycle, without which iOS 27 kills the app at launch.
 *
 * An app built against the iOS 27 SDK that still drives its window from
 * `UIApplicationDelegate` alone is stopped by UIKit as the first scene
 * connects, before any of our code or JavaScript runs. The crash is an
 * `EXC_BREAKPOINT` inside
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`, reached from
 * `-[UIApplication workspace:didCreateScene:withTransitionContext:completion:]`,
 * and the only frame of ours in it is `AppDelegate.main()`. iOS 26 only warned
 * about this, so the app starts failing the moment the toolchain is upgraded,
 * on every simulator and device running 27, with no source change of our own.
 *
 * Expo gained a flag for this in SDK 57 (`ios.enableSceneSupport` in
 * expo-build-properties) and does it by default in SDK 58. We are on SDK 55,
 * where no release carries any scene support at all -- 55.0.32, the latest
 * patch, has no `SceneDelegate`, no `UIWindowScene` and no manifest key
 * anywhere in the package. So the adoption is written out here, and this plugin
 * can be deleted whole on the SDK upgrade that brings the real thing.
 *
 * A manifest on its own is not enough: UIKit wants a scene delegate that
 * actually owns a window. Both halves are below.
 *
 * This lives in a plugin rather than in `ios/` because `ios/` is gitignored and
 * regenerated by `expo prebuild`; an edit made directly to `Info.plist` or
 * `AppDelegate.swift` is lost on the next run.
 */

const MARKER = '@treemapper-scene-lifecycle'

/**
 * The delegate class is named through `$(PRODUCT_MODULE_NAME)` rather than
 * hardcoding `TreeMapper`, so a rename of the target cannot leave the manifest
 * pointing at a class that no longer exists -- which fails the same way as no
 * manifest at all.
 */
const withSceneManifest = (config) =>
  withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      // The app has one window. Multiple scenes would mean several React roots
      // and several Realm-backed sessions, which nothing here is written for.
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    }

    return cfg
  })

/**
 * What the app delegate used to do at launch, and who takes it over.
 *
 * The Expo template builds the window in `didFinishLaunchingWithOptions` and
 * starts React Native into it. Under scenes that is too early: the window has
 * to belong to the `UIWindowScene`, which does not exist yet. So the launch
 * method keeps building the factory and now only remembers its launch options,
 * and `SceneDelegate.scene(_:willConnectTo:options:)` creates the window and
 * starts React Native.
 */
const IMPORT_ANCHOR = 'import ReactAppDependencyProvider'

// The template reaches UIKit only through React's umbrella header. The scene
// types are named directly here, so the import is made explicit.
const IMPORT_REPLACEMENT = `import ReactAppDependencyProvider
import UIKit`

const PROPERTIES_ANCHOR = `  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?`

const PROPERTIES_REPLACEMENT = `  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?

  // ${MARKER}: read by SceneDelegate, which starts React Native once it has a
  // window. React Native reads the initial deep link out of this dictionary
  // (RCTLinkingManager.getInitialURL), so the scene adds the cold-start URL to
  // it before handing it over.
  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?`

const WINDOW_ANCHOR = `#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif`

const WINDOW_REPLACEMENT = `    // ${MARKER}: the window belongs to the scene now, so it cannot be built
    // here. SceneDelegate picks these up in scene(_:willConnectTo:options:).
    self.launchOptions = launchOptions`

/**
 * The scene delegate.
 *
 * Three jobs, and each one is something that silently stops working the moment
 * a scene exists and nothing forwards it:
 *
 *  1. **The window.** Built from the `UIWindowScene`, then handed to the
 *     React Native factory, which makes the root view controller and shows it.
 *     It is also written back onto the app delegate, because
 *     `expo-system-ui` and friends read `UIApplication.shared.delegate?.window`
 *     and would otherwise find nothing.
 *  2. **URLs and universal links.** UIKit delivers these to the scene, not to
 *     the app delegate, so the Auth0 sign-in callback, the `applinks:` invite
 *     links and Garmin Connect's device-picker return (its subscriber watches
 *     `application(_:open:options:)`) all stop arriving unless they are passed
 *     along. Everything is routed back through the app delegate's own methods
 *     rather than to `RCTLinkingManager` directly, so the Expo subscribers
 *     behind \`super\` keep seeing them exactly as before.
 *  3. **Foreground and background.** UIKit stops calling
 *     \`applicationDidBecomeActive\` and the rest on the app delegate once
 *     scenes are adopted. React Native's own \`AppState\` is safe either way,
 *     since \`RCTAppState\` observes \`NSNotificationCenter\` and those
 *     notifications still post -- that is what keeps the sync queue and the
 *     activity-log cleanup running on foreground. The app delegate is called
 *     anyway so that an Expo subscriber added later behaves as its author
 *     expects. There is no double call: these are the events UIKit no longer
 *     delivers.
 */
const SCENE_DELEGATE = `
// ${MARKER} begin -- see plugins/withSceneLifecycle.js
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    return UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = appDelegate,
      let factory = appDelegate.reactNativeFactory
    else {
      return
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // A cold start from a link arrives here, not in the app delegate's launch
    // options, so the keys RCTLinkingManager.getInitialURL looks for are added
    // back before React Native starts. Without this a link that launches the
    // app opens it on the default screen.
    var launchOptions = appDelegate.launchOptions ?? [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    if let userActivity = connectionOptions.userActivities.first {
      let userActivityDictionary: [String: Any] = [
        UIApplication.LaunchOptionsKey.userActivityType.rawValue: userActivity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": userActivity
      ]
      launchOptions[.userActivityDictionary] = userActivityDictionary
    }

    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)

    // Delivered to the subscribers as well, which is what UIKit did before
    // scenes: a cold start from a URL reached both the launch options and
    // application(_:open:options:).
    for context in connectionOptions.urlContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
    for userActivity in connectionOptions.userActivities {
      _ = appDelegate.application(
        UIApplication.shared,
        continue: userActivity,
        restorationHandler: { _ in })
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let appDelegate = appDelegate else { return }
    for context in URLContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    guard let appDelegate = appDelegate else { return }
    _ = appDelegate.application(
      UIApplication.shared,
      continue: userActivity,
      restorationHandler: { _ in })
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }
}
// ${MARKER} end
`

const withSceneDelegate = (config) =>
  withAppDelegate(config, (cfg) => {
    let contents = cfg.modResults.contents

    if (contents.includes(MARKER)) {
      return cfg
    }

    // Both anchors are the stock Expo SDK 55 template. If an upgrade changes
    // either one, fail the prebuild here rather than produce a build that
    // crashes on launch with no explanation.
    for (const anchor of [IMPORT_ANCHOR, PROPERTIES_ANCHOR, WINDOW_ANCHOR]) {
      if (!contents.includes(anchor)) {
        throw new Error(
          `withSceneLifecycle: AppDelegate.swift does not contain the expected block:\n\n${anchor}\n\n` +
            'The Expo template changed. Check whether this SDK adopts the ' +
            'UIScene life cycle on its own, and delete this plugin if it does.',
        )
      }
    }

    contents = contents.replace(IMPORT_ANCHOR, IMPORT_REPLACEMENT)
    contents = contents.replace(PROPERTIES_ANCHOR, PROPERTIES_REPLACEMENT)
    contents = contents.replace(WINDOW_ANCHOR, WINDOW_REPLACEMENT)
    contents = `${contents.trimEnd()}\n${SCENE_DELEGATE}`

    cfg.modResults.contents = contents
    return cfg
  })

const withSceneLifecycle = (config) =>
  withSceneDelegate(withSceneManifest(config))

module.exports = withSceneLifecycle
