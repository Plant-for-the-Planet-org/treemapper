const { withPodfile, withXcodeProject } = require('expo/config-plugins')

/**
 * Raises every target in the Pods project to the app's minimum iOS version.
 *
 * Xcode 27 turned a deployment target below iOS 15 from a warning into a build
 * error, and several pods still declare older ones in their own podspecs.
 *
 * React Native already has a pass for this,
 * `ReactNativePodsUtils.updateOSDeploymentTarget`, called from
 * `react_native_post_install`. It walks
 * `installer.target_installation_results.pod_target_installation_results` and
 * touches each result's `native_target`, which is the pod's library target
 * only. Resource bundle targets are a separate list and are never visited, so
 * they keep whatever their podspec said. That is why the library target of
 * Auth0 builds at 15.1 while the `Auth0-Auth0` bundle beside it sits at 14.0,
 * and the same for `RNCAsyncStorage_resources` (13.4), `RNSVGFilters` (12.4),
 * `RealmJS-RealmJS` (9.0) and `SDWebImage-SDWebImage` (9.0).
 *
 * `expo-build-properties` does not cover these either: its
 * `ios.deploymentTarget` writes `platform :ios` into the Podfile and rewrites
 * the app project, and CocoaPods takes the podspec's value for a bundle rather
 * than the platform line.
 *
 * Walking `pods_project.targets` catches every target of every kind, bundles
 * included.
 *
 * The app project needs the same treatment for a second reason. The
 * OneSignal notification service extension is created by
 * onesignal-expo-plugin, which defaults the target to 11.0
 * (`dist/index.js`, `props?.iPhoneDeploymentTarget ?? "11.0"`). Setting
 * `iPhoneDeploymentTarget` in app.json fixes that at creation, but the plugin
 * logs "already exists in project. Skipping..." on every later prebuild and
 * never revisits the build settings, so an `ios/` folder that already has the
 * target keeps 11.0 until someone runs `prebuild --clean`. expo-build-properties
 * does not catch it either: its rewrite filters to `TargetType.APPLICATION`,
 * and an extension is not one. Walking every build configuration fixes the
 * project in place, clean prebuild or not.
 *
 * This lives in a plugin rather than in `ios/Podfile` because `ios/` is
 * gitignored and regenerated by `expo prebuild`; an edit made directly in the
 * Podfile or the Xcode project is lost on the next prebuild.
 */
const MARKER = '# @treemapper-pod-deployment-target'
const ANCHOR = 'post_install do |installer|'

const snippet = (target) => `
${MARKER} begin -- see plugins/withPodDeploymentTarget.js
    # Runs before react_native_post_install on purpose. That pass takes the
    # max of the existing value and its own minimum, so it can only raise what
    # is set here, never lower it.
    pod_projects = installer.respond_to?(:generated_projects) ?
      installer.generated_projects : [installer.pods_project]
    pod_projects.compact.each do |pod_project|
      pod_project.targets.each do |pod_target|
        pod_target.build_configurations.each do |pod_config|
          current = pod_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
          if current.nil? || current.to_f < ${target}
            pod_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${target}'
          end
        end
      end
    end
${MARKER} end`

/** Raise every build configuration in the app project itself. */
const withAppProjectDeploymentTarget = (config, target) =>
  withXcodeProject(config, (cfg) => {
    const section = cfg.modResults.pbxXCBuildConfigurationSection()
    const minimum = parseFloat(target)

    for (const entry of Object.values(section)) {
      const settings = entry?.buildSettings
      const current = settings?.IPHONEOS_DEPLOYMENT_TARGET
      if (current === undefined) continue
      if (parseFloat(String(current).replace(/"/g, '')) < minimum) {
        settings.IPHONEOS_DEPLOYMENT_TARGET = target
      }
    }

    return cfg
  })

const withPodsDeploymentTarget = (config, target) =>
  withPodfile(config, (cfg) => {
    const contents = cfg.modResults.contents

    if (contents.includes(MARKER)) {
      return cfg
    }
    if (!contents.includes(ANCHOR)) {
      throw new Error(
        `withPodDeploymentTarget: no "${ANCHOR}" in the generated Podfile`,
      )
    }

    cfg.modResults.contents = contents.replace(
      ANCHOR,
      `${ANCHOR}${snippet(target)}`,
    )
    return cfg
  })

const withPodDeploymentTarget = (config, props = {}) => {
  const target = props.deploymentTarget ?? '15.1'
  return withAppProjectDeploymentTarget(
    withPodsDeploymentTarget(config, target),
    target,
  )
}

module.exports = withPodDeploymentTarget
