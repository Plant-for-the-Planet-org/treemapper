const { withAppBuildGradle } = require('expo/config-plugins')

/**
 * Teaches the Android release build to sign with the Play upload key.
 *
 * The stock Expo template signs `release` with the *debug* keystore, which
 * Play rejects. This swaps in a real `signingConfigs.release` whose values all
 * come from Gradle properties, so no credential and no keystore path ever
 * lands in this repo -- which is public.
 *
 * Set these in `~/.gradle/gradle.properties` (outside the repo, so they cannot
 * be committed even by accident):
 *
 *   TREEMAPPER_UPLOAD_STORE_FILE=/absolute/path/to/upload.keystore
 *   TREEMAPPER_UPLOAD_STORE_PASSWORD=...
 *   TREEMAPPER_UPLOAD_KEY_ALIAS=...
 *   TREEMAPPER_UPLOAD_KEY_PASSWORD=...
 *
 * With none of them set, a release build still works and is still signed with
 * the debug key -- today's behaviour -- but Gradle warns loudly, because a
 * silently debug-signed build is the easy way to upload the wrong artifact.
 *
 * This lives in a plugin rather than in `android/app/build.gradle` because
 * `android/` is gitignored and regenerated by `expo prebuild`; an edit made
 * directly in the gradle file is lost on the next prebuild and never reaches
 * anyone else. See plugins/withCameraCompatOptOut.js for the same reasoning.
 */
const MARKER = 'TREEMAPPER_UPLOAD_STORE_FILE'

const DEBUG_SIGNING_CONFIG = `        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }`

const RELEASE_SIGNING_CONFIG = `
        release {
            // All four values come from ~/.gradle/gradle.properties.
            // Never hardcode them here: this repo is public.
            def uploadStorePath = findProperty('TREEMAPPER_UPLOAD_STORE_FILE')
            if (uploadStorePath) {
                storeFile file(uploadStorePath.replaceFirst('^~', System.getProperty('user.home')))
                storePassword findProperty('TREEMAPPER_UPLOAD_STORE_PASSWORD')
                keyAlias findProperty('TREEMAPPER_UPLOAD_KEY_ALIAS')
                keyPassword findProperty('TREEMAPPER_UPLOAD_KEY_PASSWORD')
            }
        }`

const DEBUG_SIGNED_RELEASE = `            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`

const UPLOAD_SIGNED_RELEASE = `            // Signed with the upload key when it is configured, and loudly
            // debug-signed when it is not. See plugins/withReleaseSigning.js.
            // Explicit null check, not ?.exists(): Gradle instruments File.exists()
            // for configuration-cache input tracking and that hook rejects a null
            // receiver outright, so safe navigation still blows up when the
            // keystore property is unset.
            def uploadKeystore = signingConfigs.release.storeFile
            if (uploadKeystore != null && uploadKeystore.exists()) {
                signingConfig signingConfigs.release
            } else {
                project.logger.warn("TreeMapper: no upload keystore configured (TREEMAPPER_UPLOAD_STORE_FILE in ~/.gradle/gradle.properties). This release build is signed with the DEBUG key and Play will reject it.")
                signingConfig signingConfigs.debug
            }`

const withReleaseSigning = (config) =>
  withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error(
        `withReleaseSigning: expected a Groovy build.gradle, got ${cfg.modResults.language}`,
      )
    }

    let contents = cfg.modResults.contents

    // Idempotent: prebuild can run the mods more than once.
    if (contents.includes(MARKER)) {
      return cfg
    }

    if (!contents.includes(DEBUG_SIGNING_CONFIG)) {
      throw new Error(
        'withReleaseSigning: could not find the debug signingConfig block in ' +
          'android/app/build.gradle. The Expo template changed -- update the ' +
          'anchor in this plugin.',
      )
    }
    contents = contents.replace(
      DEBUG_SIGNING_CONFIG,
      () => DEBUG_SIGNING_CONFIG + RELEASE_SIGNING_CONFIG,
    )

    if (!contents.includes(DEBUG_SIGNED_RELEASE)) {
      throw new Error(
        'withReleaseSigning: could not find the debug-signed release buildType ' +
          'in android/app/build.gradle. The Expo template changed -- update the ' +
          'anchor in this plugin.',
      )
    }
    contents = contents.replace(DEBUG_SIGNED_RELEASE, () => UPLOAD_SIGNED_RELEASE)

    cfg.modResults.contents = contents
    return cfg
  })

module.exports = withReleaseSigning
