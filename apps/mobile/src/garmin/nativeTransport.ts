import { NativeEventEmitter, NativeModules, Platform } from 'react-native'
import { GarminCommand } from './protocol'
import {
  GarminLinkEvent,
  GarminLinkListener,
  GarminTransport,
} from './transport'

/**
 * The native Connect IQ link. It does not exist yet.
 *
 * This file is the contract the native module has to meet, written down now so
 * the JS above it is finished and the native work is a drop-in rather than a
 * refactor. `createNativeTransport` returns null until the module is there,
 * and everything upstream already copes with null.
 *
 * What has to be built, per platform:
 *
 * **Android.** A local Expo module (`apps/mobile/modules/`), because
 * `android/` here is generated by prebuild and a hand edit would not survive.
 * It needs `com.garmin.connectiq:ciq-companion-app-sdk:2.4.0@aar` from Maven
 * Central, a `<queries>` entry for `com.garmin.android.apps.connectmobile` in
 * the manifest (without it the SDK cannot see Garmin Connect on Android 11+
 * and fails with a confusing "service unavailable"), and `BLUETOOTH_CONNECT`.
 * The watch repo's `android-demo/.../WatchLink.kt` is a working reference and
 * ports almost directly.
 *
 * **iOS.** Harder, and not for free: the Connect IQ iOS SDK is a framework
 * downloaded by hand from Garmin's developer portal, not a package. It also
 * needs the URL-scheme handoff with Garmin Connect for device discovery, and
 * an `LSApplicationQueriesSchemes` entry. Until that lands this returns null
 * on iOS and the button simply does not appear.
 *
 * The native module must expose:
 *
 *   start(): void            // initialize, discover, register listeners
 *   stop(): void
 *   send(command: object): void
 *   openWatchApp(): void
 *   openStore(): void
 *
 * and emit one event, `GarminLinkEvent`, carrying the union in
 * `transport.ts`. Emitting the raw payload unparsed is deliberate: the parser
 * lives in `protocol.ts` and is shared with the mock, so there is one place
 * where a wire format change has to be understood.
 */

const NATIVE_MODULE_NAME = 'TreeMapperGarmin'
const NATIVE_EVENT_NAME = 'GarminLinkEvent'

interface GarminNativeModule {
  start(): void
  stop(): void
  send(command: GarminCommand): void
  openWatchApp(): void
  openStore(): void
}

const nativeModule: GarminNativeModule | undefined =
  NativeModules?.[NATIVE_MODULE_NAME]

/** True once the native module ships. Nothing else should test for it. */
export const hasNativeGarminLink = (): boolean =>
  !!nativeModule && Platform.OS === 'android'

export const createNativeTransport = (): GarminTransport | null => {
  if (!nativeModule || !hasNativeGarminLink()) {
    return null
  }

  const emitter = new NativeEventEmitter(
    NativeModules[NATIVE_MODULE_NAME] as never,
  )
  let subscription: { remove: () => void } | null = null

  return {
    name: 'connect-iq',

    start(listener: GarminLinkListener) {
      subscription = emitter.addListener(
        NATIVE_EVENT_NAME,
        (event: GarminLinkEvent) => listener(event),
      )
      nativeModule.start()
    },

    stop() {
      subscription?.remove()
      subscription = null
      nativeModule.stop()
    },

    send(command: GarminCommand) {
      nativeModule.send(command)
    },

    openWatchApp() {
      nativeModule.openWatchApp()
    },

    openStore() {
      nativeModule.openStore()
    },
  }
}
