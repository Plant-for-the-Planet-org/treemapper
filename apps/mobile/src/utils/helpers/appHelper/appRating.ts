import { Linking, Platform } from 'react-native'
import * as StoreReview from 'expo-store-review'
import { AppRatingState } from 'src/types/interface/slice.interface'

// ── Store identifiers ────────────────────────────────────────────────────────
// Android reads the applicationId; iOS needs the numeric App Store id from the
// listing url (apps.apple.com/app/treemapper/id1524353784).
export const ANDROID_PACKAGE = 'org.pftp.treemapper'
export const IOS_APP_STORE_ID = '1524353784'

// ── When to ask ──────────────────────────────────────────────────────────────
// Two happy moments before the first ask, and at least ~45 days between asks so
// someone who taps "Not now" is never nagged.
export const MIN_POSITIVE_EVENTS = 2
export const REPROMPT_INTERVAL_MS = 45 * 24 * 60 * 60 * 1000

export const defaultRatingState: AppRatingState = {
  eventCount: 0,
  lastAskedAt: 0,
  hasRated: false,
  dontAskAgain: false,
}

/**
 * Decides whether the "Are you enjoying TreeMapper?" pre-prompt may show.
 * Pure so it can be unit-tested; `now` is passed in rather than read here.
 */
export function shouldShowRatingPrompt(
  rating: AppRatingState | undefined,
  now: number = Date.now(),
): boolean {
  const r = { ...defaultRatingState, ...(rating ?? {}) }
  if (r.hasRated || r.dontAskAgain) return false
  if (r.eventCount < MIN_POSITIVE_EVENTS) return false
  if (r.lastAskedAt !== 0 && now - r.lastAskedAt < REPROMPT_INTERVAL_MS) return false
  return true
}

/**
 * Fires the OS in-app review flow (SKStoreReviewController on iOS, Play In-App
 * Review on Android). The OS decides whether it actually appears and returns
 * nothing, so this is best-effort. Resolves true only when the native call was
 * made, letting callers fall back to the store listing when it was not.
 */
export async function requestNativeReview(): Promise<boolean> {
  try {
    const available = await StoreReview.isAvailableAsync()
    const hasAction = await StoreReview.hasAction()
    if (available && hasAction) {
      await StoreReview.requestReview()
      return true
    }
  } catch {
    // A review prompt must never affect the app.
  }
  return false
}

/**
 * Every way we know of to reach a rating surface, best first: the native store
 * app on the write-review screen, then the same listing on the web, then the
 * in-app sheet.
 *
 * Deliberately no `Linking.canOpenURL`. On Android 11+ package visibility makes
 * it return false for `market://` unless the app declares a <queries> entry, so
 * it reports "cannot open" for a url that `openURL` opens perfectly well. The
 * manifest is generated by prebuild here, so that entry would need a config
 * plugin. Trying `openURL` and catching the throw is both simpler and truthful.
 */
function storeUrls(): string[] {
  return Platform.OS === 'ios'
    ? [
        `itms-apps://itunes.apple.com/app/id${IOS_APP_STORE_ID}?action=write-review`,
        `https://apps.apple.com/app/id${IOS_APP_STORE_ID}?action=write-review`,
      ]
    : [
        `market://details?id=${ANDROID_PACKAGE}`,
        `https://play.google.com/store/apps/details?id=${ANDROID_PACKAGE}`,
      ]
}

/**
 * Opens the store listing on the write-review screen. Used by the manual
 * "Rate the app" entry, where the person explicitly asked to rate and a
 * deterministic jump to the store beats the throttled native sheet.
 *
 * Returns whether anything actually opened, so the caller can tell a real
 * rating from a silent no-op. That matters more than it looks: the native
 * sheet does nothing at all in a build that was not installed from the store,
 * and reports no error when it declines to appear.
 */
export async function openStoreListing(): Promise<boolean> {
  for (const url of storeUrls()) {
    try {
      await Linking.openURL(url)
      return true
    } catch {
      // No handler for this scheme; try the next one.
    }
  }
  return requestNativeReview()
}
